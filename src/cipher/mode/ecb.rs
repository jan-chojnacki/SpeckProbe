    fn known_vector(
        #[case] version: SpeckVersion,
        #[case] key: Vec<u8>,
        #[case] plaintext: Vec<u8>,
        #[case] ciphertext: Vec<u8>,
    ) {
        let speck = make_ecb(version, &key);
        let block_size = version.block_size_bytes();

        let ct = speck.encrypt(&plaintext).unwrap();
        assert_eq!(&ct[..block_size], ciphertext.as_slice());

        let pt = speck.decrypt(&ciphertext).unwrap();
        assert_eq!(pt, plaintext);
    }

